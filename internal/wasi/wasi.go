// Package wasi implements the subset of WASI preview1 that libgit2 imports
// when built against wasi-libc, over a read-only filesystem.
//
// It supports a single preopened directory, with no sockets and no
// environment, and every call that would modify a file fails with EROFS.
// Reads go directly into the module's linear memory, so steady-state I/O
// does no Go allocations.
package wasi

import (
	"crypto/rand"
	"encoding/binary"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"runtime"
	"strings"
	"syscall"
	"time"
)

// Errno values from the WASI preview1 specification.
const (
	errnoSuccess     = 0
	errnoAcces       = 2
	errnoBadf        = 8
	errnoExist       = 20
	errnoInval       = 28
	errnoIO          = 29
	errnoIsdir       = 31
	errnoLoop        = 32
	errnoNametoolong = 37
	errnoNoent       = 44
	errnoNotdir      = 54
	errnoPerm        = 63
	errnoRofs        = 68
	errnoSpipe       = 70
	errnoNotcapable  = 76
)

// File types from the WASI preview1 specification.
const (
	filetypeUnknown   = 0
	filetypeCharDev   = 2
	filetypeDirectory = 3
	filetypeRegular   = 4
	filetypeSymlink   = 7
)

const (
	oflagsCreat     = 1 << 0
	oflagsDirectory = 1 << 1
	oflagsExcl      = 1 << 2
	oflagsTrunc     = 1 << 3

	lookupSymlinkFollow = 1 << 0

	// Rights that imply mutation of the opened file.
	rightFdWrite           = 1 << 6
	rightFdAllocate        = 1 << 8
	rightFdFilestatSetSize = 1 << 22

	preopenFD = 3
)

// File is an open file or directory.
type File interface {
	io.Reader
	io.ReaderAt
	io.Seeker
	io.Closer
	Stat() (fs.FileInfo, error)
	ReadDir(n int) ([]fs.DirEntry, error)
}

// FS is a read-only filesystem rooted at the preopened directory. Names are
// slash-separated, relative and unrooted, as for io/fs.
type FS interface {
	Open(name string) (File, error)
	Stat(name string) (fs.FileInfo, error)
	Lstat(name string) (fs.FileInfo, error)
	Readlink(name string) (string, error)
}

// Memory is the module's linear memory as exposed by wasm2go.
type Memory interface {
	Slice() *[]byte
}

type fdEntry struct {
	f    File
	name string        // io/fs name the file was opened as
	dir  []fs.DirEntry // lazily populated for fd_readdir
	read bool          // dir has been populated
}

// Host implements the wasi_snapshot_preview1 import interface generated by
// wasm2go. Like the module, it is not safe for concurrent use.
type Host struct {
	mem   Memory
	fs    FS
	mount string
	fds   []*fdEntry // indexed by guest fd, with 0-3 reserved
	free  []int32
}

// New returns a Host exposing fsys to the guest at the absolute path mount.
func New(mem Memory, fsys FS, mount string) *Host {
	return &Host{
		mem:   mem,
		fs:    fsys,
		mount: mount,
		fds:   make([]*fdEntry, preopenFD+1),
	}
}

// m returns linear memory, with its capacity cut to its length so that an
// access past the module's memory panics, as one by the module traps,
// instead of reaching the rest of the reservation.
func (h *Host) m() []byte {
	b := *h.mem.Slice()
	return b[:len(b):len(b)]
}

func (h *Host) str(ptr, n int32) string {
	b := h.m()[uint32(ptr) : uint32(ptr)+uint32(n)]
	return string(b)
}

func le32(b []byte, off uint32, v uint32) { binary.LittleEndian.PutUint32(b[off:], v) }
func le64(b []byte, off uint32, v uint64) { binary.LittleEndian.PutUint64(b[off:], v) }

func errno(err error) int32 {
	if err == nil {
		return errnoSuccess
	}
	var errNo syscall.Errno
	if errors.As(err, &errNo) {
		switch errNo {
		case syscall.ENOENT:
			return errnoNoent
		case syscall.ENOTDIR:
			// On Windows this is ERROR_PATH_NOT_FOUND, which mostly means a
			// parent directory is missing. Its C runtime reports ENOENT.
			if runtime.GOOS == "windows" {
				return errnoNoent
			}
			return errnoNotdir
		case syscall.EISDIR:
			return errnoIsdir
		case syscall.EACCES:
			return errnoAcces
		case syscall.EPERM:
			return errnoPerm
		case syscall.ELOOP:
			return errnoLoop
		case syscall.EEXIST:
			return errnoExist
		case syscall.ENAMETOOLONG:
			return errnoNametoolong
		case syscall.EINVAL:
			return errnoInval
		}
	}
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return errnoNoent
	case errors.Is(err, fs.ErrPermission):
		return errnoPerm
	case errors.Is(err, fs.ErrInvalid):
		return errnoInval
	}
	return errnoIO
}

func (h *Host) file(fd int32) *fdEntry {
	if fd <= preopenFD || int(fd) >= len(h.fds) {
		return nil
	}
	return h.fds[fd]
}

func (h *Host) alloc(e *fdEntry) int32 {
	if n := len(h.free); n > 0 {
		fd := h.free[n-1]
		h.free = h.free[:n-1]
		h.fds[fd] = e
		return fd
	}
	h.fds = append(h.fds, e)
	return int32(len(h.fds) - 1)
}

// Close releases every file the guest left open.
func (h *Host) Close() error {
	for i, e := range h.fds {
		if e != nil {
			e.f.Close()
			h.fds[i] = nil
		}
	}
	return nil
}

func (h *Host) Xargs_sizes_get(argc, bufSize int32) int32 {
	m := h.m()
	le32(m, uint32(argc), 0)
	le32(m, uint32(bufSize), 0)
	return errnoSuccess
}

func (h *Host) Xargs_get(argv, buf int32) int32 { return errnoSuccess }

func (h *Host) Xenviron_sizes_get(count, bufSize int32) int32 {
	m := h.m()
	le32(m, uint32(count), 0)
	le32(m, uint32(bufSize), 0)
	return errnoSuccess
}

func (h *Host) Xenviron_get(environ, buf int32) int32 { return errnoSuccess }

func (h *Host) Xclock_time_get(id int32, precision int64, out int32) int32 {
	var t int64
	switch id {
	case 0: // realtime
		t = time.Now().UnixNano()
	case 1, 2, 3: // monotonic, process and thread cputime
		t = int64(time.Since(epoch))
	default:
		return errnoInval
	}
	le64(h.m(), uint32(out), uint64(t))
	return errnoSuccess
}

var epoch = time.Now()

func (h *Host) Xrandom_get(buf, n int32) int32 {
	rand.Read(h.m()[uint32(buf) : uint32(buf)+uint32(n)])
	return errnoSuccess
}

// ExitError is the panic value raised when the guest calls proc_exit.
type ExitError struct{ Code int32 }

func (e *ExitError) Error() string { return fmt.Sprintf("wasi: proc_exit(%d) called", e.Code) }

func (h *Host) Xproc_exit(code int32) { panic(&ExitError{code}) }

func (h *Host) Xfd_prestat_get(fd, out int32) int32 {
	if fd != preopenFD {
		return errnoBadf
	}
	m := h.m()
	le32(m, uint32(out), 0) // tag: dir
	le32(m, uint32(out)+4, uint32(len(h.mount)))
	return errnoSuccess
}

func (h *Host) Xfd_prestat_dir_name(fd, path, n int32) int32 {
	if fd != preopenFD {
		return errnoBadf
	}
	if int(n) < len(h.mount) {
		return errnoInval
	}
	copy(h.m()[uint32(path):uint32(path)+uint32(n)], h.mount)
	return errnoSuccess
}

func (h *Host) Xfd_fdstat_get(fd, out int32) int32 {
	var ft byte
	switch {
	case fd <= 2:
		ft = filetypeCharDev
	case fd == preopenFD:
		ft = filetypeDirectory
	default:
		e := h.file(fd)
		if e == nil {
			return errnoBadf
		}
		fi, err := e.f.Stat()
		if err != nil {
			return errno(err)
		}
		ft = filetype(fi.Mode())
	}
	m := h.m()
	o := uint32(out)
	clear(m[o : o+24])
	m[o] = ft
	le64(m, o+8, ^uint64(0)) // rights_base: report everything, and enforce rights on use
	le64(m, o+16, ^uint64(0))
	return errnoSuccess
}

func filetype(mode fs.FileMode) byte {
	switch {
	case mode.IsRegular():
		return filetypeRegular
	case mode.IsDir():
		return filetypeDirectory
	case mode&fs.ModeSymlink != 0:
		return filetypeSymlink
	case mode&fs.ModeCharDevice != 0:
		return filetypeCharDev
	}
	return filetypeUnknown
}

// sysStat is what a platform's file information adds to fs.FileInfo, as
// platformStat reads it.
type sysStat struct{ dev, ino, nlink, atim, ctim uint64 }

func (h *Host) writeFilestat(out int32, fi fs.FileInfo) {
	m := h.m()
	o := uint32(out)
	clear(m[o : o+64])
	// The zero time, as from filesystems without modification times, has
	// no defined UnixNano.
	var mtim uint64
	if t := fi.ModTime(); !t.IsZero() {
		mtim = uint64(t.UnixNano())
	}
	s, ok := platformStat(fi)
	if !ok {
		s = sysStat{nlink: 1, atim: mtim, ctim: mtim}
	}
	le64(m, o, s.dev)
	le64(m, o+8, s.ino)
	m[o+16] = filetype(fi.Mode())
	le64(m, o+24, s.nlink)
	le64(m, o+32, uint64(fi.Size()))
	le64(m, o+40, s.atim)
	le64(m, o+48, mtim)
	le64(m, o+56, s.ctim)
}

func (h *Host) Xfd_filestat_get(fd, out int32) int32 {
	e := h.file(fd)
	if e == nil {
		return errnoBadf
	}
	fi, err := e.f.Stat()
	if err != nil {
		return errno(err)
	}
	h.writeFilestat(out, fi)
	return errnoSuccess
}

// resolve converts a guest path relative to dirfd into an io/fs name. Empty
// and "." elements are dropped, and a path that is still not a valid io/fs
// name, such as one with ".." in it, fails with ENOTCAPABLE. The repository
// controls some paths, such as those in objects/info/alternates, and not
// every FS refuses to leave its root.
func (h *Host) resolve(dirfd, ptr, n int32) (string, int32) {
	p := relpath(h.str(ptr, n))
	if dirfd != preopenFD {
		e := h.file(dirfd)
		if e == nil {
			return "", errnoBadf
		}
		switch {
		case p == ".":
			p = e.name
		case e.name != ".":
			p = e.name + "/" + p
		}
	}
	if p = collapse(p); !fs.ValidPath(p) {
		return "", errnoNotcapable
	}
	return p, errnoSuccess
}

// collapse drops empty and "." elements from p, which never change what it
// names. Unlike path.Clean, it keeps ".." elements: resolving them could
// change the meaning of a path through symbolic links, and would hide an
// escape from the root.
func collapse(p string) string {
	if fs.ValidPath(p) {
		return p
	}
	var b strings.Builder
	for elem := range strings.SplitSeq(p, "/") {
		if elem == "" || elem == "." {
			continue
		}
		if b.Len() > 0 {
			b.WriteByte('/')
		}
		b.WriteString(elem)
	}
	if b.Len() == 0 {
		return "."
	}
	return b.String()
}

// relpath converts a guest path relative to the preopen into an io/fs name.
func relpath(p string) string {
	for len(p) > 0 && p[0] == '/' {
		p = p[1:]
	}
	for len(p) > 0 && p[len(p)-1] == '/' {
		p = p[:len(p)-1]
	}
	if p == "" {
		return "."
	}
	return p
}

func (h *Host) Xpath_filestat_get(dirfd, flags, path, n, out int32) int32 {
	name, en := h.resolve(dirfd, path, n)
	if en != errnoSuccess {
		return en
	}
	var fi fs.FileInfo
	var err error
	if flags&lookupSymlinkFollow != 0 {
		fi, err = h.fs.Stat(name)
	} else {
		fi, err = h.fs.Lstat(name)
	}
	if err != nil {
		return errno(err)
	}
	h.writeFilestat(out, fi)
	return errnoSuccess
}

func (h *Host) Xpath_open(dirfd, dirflags, path, n, oflags int32, rightsBase, rightsInheriting int64, fdflags, out int32) int32 {
	if oflags&(oflagsCreat|oflagsTrunc|oflagsExcl) != 0 ||
		rightsBase&(rightFdWrite|rightFdAllocate|rightFdFilestatSetSize) != 0 {
		return errnoRofs
	}
	name, en := h.resolve(dirfd, path, n)
	if en != errnoSuccess {
		return en
	}
	f, err := h.fs.Open(name)
	if err != nil {
		return errno(err)
	}
	if oflags&oflagsDirectory != 0 {
		fi, err := f.Stat()
		if err != nil {
			f.Close()
			return errno(err)
		}
		if !fi.IsDir() {
			f.Close()
			return errnoNotdir
		}
	}
	fd := h.alloc(&fdEntry{f: f, name: name})
	le32(h.m(), uint32(out), uint32(fd))
	return errnoSuccess
}

func (h *Host) Xfd_close(fd int32) int32 {
	e := h.file(fd)
	if e == nil {
		return errnoBadf
	}
	h.fds[fd] = nil
	h.free = append(h.free, fd)
	return errno(e.f.Close())
}

// iovecs calls fn for each (buf, len) pair of the iovec array at iovs.
func (h *Host) iovecs(iovs, count int32, fn func(b []byte) (int, error)) (int, error) {
	m := h.m()
	total := 0
	for i := range uint32(count) {
		o := uint32(iovs) + 8*i
		ptr := binary.LittleEndian.Uint32(m[o:])
		l := binary.LittleEndian.Uint32(m[o+4:])
		if l == 0 {
			continue
		}
		n, err := fn(m[ptr : ptr+l])
		total += n
		if err != nil {
			return total, err
		}
		if n < int(l) {
			break
		}
	}
	return total, nil
}

func (h *Host) Xfd_read(fd, iovs, count, out int32) int32 {
	e := h.file(fd)
	if e == nil {
		if fd == 0 {
			le32(h.m(), uint32(out), 0)
			return errnoSuccess
		}
		return errnoBadf
	}
	n, err := h.iovecs(iovs, count, func(b []byte) (int, error) {
		n, err := io.ReadFull(e.f, b)
		if err == io.ErrUnexpectedEOF || err == io.EOF {
			err = nil
		}
		return n, err
	})
	if err != nil {
		return errno(err)
	}
	le32(h.m(), uint32(out), uint32(n))
	return errnoSuccess
}

func (h *Host) Xfd_pread(fd, iovs, count int32, offset int64, out int32) int32 {
	e := h.file(fd)
	if e == nil {
		return errnoBadf
	}
	n, err := h.iovecs(iovs, count, func(b []byte) (int, error) {
		n, err := e.f.ReadAt(b, offset)
		offset += int64(n)
		if err == io.EOF {
			err = nil
		}
		return n, err
	})
	if err != nil {
		return errno(err)
	}
	le32(h.m(), uint32(out), uint32(n))
	return errnoSuccess
}

func (h *Host) Xfd_seek(fd int32, offset int64, whence, out int32) int32 {
	e := h.file(fd)
	if e == nil {
		if fd <= 2 {
			return errnoSpipe
		}
		return errnoBadf
	}
	pos, err := e.f.Seek(offset, int(whence))
	if err != nil {
		return errno(err)
	}
	le64(h.m(), uint32(out), uint64(pos))
	return errnoSuccess
}

func (h *Host) Xfd_write(fd, iovs, count, out int32) int32 {
	if fd != 1 && fd != 2 {
		if h.file(fd) == nil {
			return errnoBadf
		}
		return errnoRofs
	}
	n, err := h.iovecs(iovs, count, io.Discard.Write)
	if err != nil {
		return errno(err)
	}
	le32(h.m(), uint32(out), uint32(n))
	return errnoSuccess
}

func (h *Host) Xfd_readdir(fd, buf, bufLen int32, cookie int64, out int32) int32 {
	e := h.file(fd)
	if e == nil {
		return errnoBadf
	}
	if cookie < 0 {
		return errnoInval
	}
	if !e.read {
		ents, err := e.f.ReadDir(-1)
		if err != nil {
			return errno(err)
		}
		e.dir, e.read = ents, true
	}
	m := h.m()
	start, end := uint32(buf), uint32(buf)+uint32(bufLen)
	o := start
	var hdr [24]byte
	for i := int(cookie); i < len(e.dir) && o < end; i++ {
		d := e.dir[i]
		name := d.Name()
		binary.LittleEndian.PutUint64(hdr[0:], uint64(i+1))
		// A zero inode makes wasi-libc stat each entry. libgit2 never
		// looks at the inode, so report a synthetic one.
		binary.LittleEndian.PutUint64(hdr[8:], uint64(i+1))
		binary.LittleEndian.PutUint32(hdr[16:], uint32(len(name)))
		hdr[20] = filetype(d.Type())
		hdr[21], hdr[22], hdr[23] = 0, 0, 0
		// Partial writes are allowed. A full buffer tells the guest to call
		// again with a larger one or the next cookie.
		o += uint32(copy(m[o:end], hdr[:]))
		o += uint32(copy(m[o:end], name))
	}
	le32(m, uint32(out), o-start)
	return errnoSuccess
}

func (h *Host) Xpath_readlink(dirfd, path, n, buf, bufLen, out int32) int32 {
	name, en := h.resolve(dirfd, path, n)
	if en != errnoSuccess {
		return en
	}
	target, err := h.fs.Readlink(name)
	if err != nil {
		// realpath probes every path component with readlink and relies
		// on EINVAL for non-links. Not every FS reports it that way.
		if fi, lerr := h.fs.Lstat(name); lerr == nil && fi.Mode()&fs.ModeSymlink == 0 {
			return errnoInval
		}
		return errno(err)
	}
	c := copy(h.m()[uint32(buf):uint32(buf)+uint32(bufLen)], target)
	le32(h.m(), uint32(out), uint32(c))
	return errnoSuccess
}

